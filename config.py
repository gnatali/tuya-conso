# -*- coding: utf-8 -*-
"""
config.py -- loads configuration from .env, optionally overridden by
tinytuya.json (generated by `python -m tinytuya wizard`).
"""

import os
import sys
import json
import datetime as dt
from pathlib import Path
from dotenv import load_dotenv

load_dotenv()  # load .env if present

_TINYTUYA_JSON = Path(__file__).resolve().parent / "tinytuya.json"


def _required(name):
    value = os.getenv(name, "").strip()
    if not value or value.startswith("YOUR_"):
        sys.exit(
            f"[config] Variable {name} is not set.\n"
            f"          Copy .env.example to .env and fill it in:\n"
            f"          cp .env.example .env"
        )
    return value


def _load_tinytuya_json():
    if not _TINYTUYA_JSON.exists():
        return None
    try:
        with open(_TINYTUYA_JSON, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        sys.exit(f"[config] {_TINYTUYA_JSON.name} is unreadable: {e}")


_wizard_config = _load_tinytuya_json()

if _wizard_config:
    # tinytuya.json (from `python -m tinytuya wizard`) takes precedence over .env
    print(f"[config] {_TINYTUYA_JSON.name} found -> used instead of .env "
          f"for the connection (region/keys/device).")
    API_REGION = (_wizard_config.get("apiRegion") or "eu").strip()
    API_KEY = (_wizard_config.get("apiKey") or "").strip()
    API_SECRET = (_wizard_config.get("apiSecret") or "").strip()
    DEVICE_ID = (_wizard_config.get("apiDeviceID") or "").strip()
    if not (API_KEY and API_SECRET and DEVICE_ID):
        sys.exit(
            f"[config] {_TINYTUYA_JSON.name} is incomplete (apiKey/apiSecret/apiDeviceID "
            f"required). Re-run: python -m tinytuya wizard"
        )
else:
    API_REGION = os.getenv("TUYA_API_REGION", "eu").strip() or "eu"
    API_KEY = _required("TUYA_API_KEY")
    API_SECRET = _required("TUYA_API_SECRET")
    DEVICE_ID = _required("TUYA_DEVICE_ID")

# Installation date
_install_date_str = os.getenv("INSTALL_DATE", "2022-01-01").strip()
try:
    INSTALL_DATE = dt.datetime.strptime(_install_date_str, "%Y-%m-%d").date()
except ValueError:
    sys.exit(f"[config] Invalid INSTALL_DATE: '{_install_date_str}' (expected YYYY-MM-DD)")

# Energy quantity code (None = auto-detect)
_energy_code_str = os.getenv("ENERGY_CODE", "").strip()
ENERGY_CODE = _energy_code_str if _energy_code_str else None

# Output files
CSV_DAILY = "daily_consumption_history.csv"
CSV_MONTHLY = "monthly_consumption_history.csv"
